"""Google Antigravity: plugins under antigravity/plugins, one always-on rules/AGENTS.md per plugin.

Antigravity loads a plugin's rules file whole while the plugin is enabled, so each section carries a scope
line built from the source rule's `paths:` globs. The bundled rules.md caps a rules file at 24,000 bytes.
"""
import re

from engine import paths_of, render, split_frontmatter
from targets.base import Output, Target

RULES_LIMIT = 24_000
HEADER = '<!-- Generated by scripts/build/build.py from src/rules. Do not edit by hand. -->'
INTRO = ('These rules apply while this plugin is enabled. The Claude layer scopes each section to file paths. '
         'Antigravity loads the whole file, so apply each section to the files its scope line names.')


class Antigravity(Target):
    name = 'antigravity'

    def skill_ref(self, kit, skill):
        return self.flat_name(kit, skill)

    def invoke(self, kit, skill):
        return f'/{self.flat_name(kit, skill)}'

    def owned_roots(self):
        return [f'antigravity/plugins/{spec["kit"]}/rules' for spec in self.config.get('rule_files', [])]

    def outputs(self, project):
        return [self.rules_file(project, spec) for spec in self.config.get('rule_files', [])]

    def rules_file(self, project, spec):
        kit = spec['kit']
        delegation_rel = f'src/rules/delegation/{kit}.md'
        delegation = render(project.read(delegation_rel), self, delegation_rel).strip()
        parts = [f'# {spec["title"]}', '', HEADER, '', INTRO, '', '## Subagents and delegation', '', delegation]
        for rel in spec['sources']:
            raw = project.read(rel)
            _, body = split_frontmatter(raw)
            body = render(body, self, rel).strip()
            body = re.sub(r'^# ', '## ', body, count=1, flags=re.M)
            parts += ['', body]
            globs = paths_of(raw)
            if globs:
                parts += ['', 'Scope: ' + ', '.join(f'`{g}`' for g in globs) + '.']
        content = ('\n'.join(parts).rstrip() + '\n').encode()
        path = f'antigravity/plugins/{kit}/rules/AGENTS.md'
        if len(content) > RULES_LIMIT:
            raise ValueError(f'{path} is {len(content)} bytes, over the {RULES_LIMIT} byte rules limit')
        return Output(path, content)
