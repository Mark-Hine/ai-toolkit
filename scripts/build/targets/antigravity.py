"""Google Antigravity: plugins under antigravity/plugins, one always-on rules/AGENTS.md per plugin.

Antigravity loads a plugin's rules file whole while the plugin is enabled, so each section carries a scope
line built from the source rule's `paths:` globs. The bundled rules.md caps a rules file at 24,000 bytes.
"""
import re

from engine import apply_tokens, parse_frontmatter, paths_of, render, split_frontmatter
from targets.base import Output, Target, emit

RULES_LIMIT = 24_000
HEADER = '<!-- Generated by scripts/build/build.py from src/rules. Do not edit by hand. -->'
INTRO = ('These rules apply while this plugin is enabled. The Claude layer scopes each section to file paths. '
         'Antigravity loads the whole file, so apply each section to the files its scope line names.')


class Antigravity(Target):
    name = 'antigravity'

    def skill_ref(self, kit, skill):
        return self.flat_name(kit, skill)

    def invoke(self, kit, skill):
        return f'/{self.flat_name(kit, skill)}'

    def skill_dir(self, kit, skill):
        return f'antigravity/plugins/{kit}/skills/{self.flat_name(kit, skill)}'

    def agent_path(self, kit, agent):
        return f'antigravity/plugins/{kit}/agents/{agent}.md'

    def owned_roots(self, project):
        roots = [f'antigravity/plugins/{spec["kit"]}/rules' for spec in self.config.get('rule_files', [])]
        roots += [f'antigravity/plugins/{kit}/agents' for kit in project.agent_kits]
        return roots + super().owned_roots(project)

    def outputs(self, project):
        rules = [self.rules_file(project, spec) for spec in self.config.get('rule_files', [])]
        return rules + super().outputs(project)

    def skill_frontmatter(self, skill, entries, fields):
        return self.flat_skill_frontmatter(skill, entries, fields)

    def agent_output(self, agent):
        block, body = split_frontmatter(agent.text)
        fields, skills = self.agent_frontmatter(agent, parse_frontmatter(block))
        lines = [emit('name', fields['name']), emit('description', apply_tokens(fields['description'], self, agent.source))]
        for key, value in self.role_fields(agent).items():
            if key == 'skills':
                if value and skills:
                    lines.append('skills: [' + ', '.join(f'skills/{self.flat_name(*s)}' for s in skills) + ']')
                continue
            if isinstance(value, bool):
                value = 'true' if value else 'false'
            elif isinstance(value, list):
                value = '[' + ', '.join(value) + ']'
            lines.append(f'{key}: {apply_tokens(str(value), self, agent.source)}')
        text = '---\n' + '\n'.join(lines) + '\n---\n' + self.agent_body(agent, body)
        return Output(self.agent_path(agent.kit, agent.name), text.encode())

    def rules_file(self, project, spec):
        kit = spec['kit']
        delegation_rel = f'src/rules/delegation/{kit}.md'
        delegation = render(project.read(delegation_rel), self, delegation_rel).strip()
        parts = [f'# {spec["title"]}', '', HEADER, '', INTRO, '', '## Subagents and delegation', '', delegation]
        for rel in spec['sources']:
            raw = project.read(rel)
            _, body = split_frontmatter(raw)
            body = render(body, self, rel).strip()
            body = re.sub(r'^# ', '## ', body, count=1, flags=re.M)
            parts += ['', body]
            globs = paths_of(raw)
            if globs:
                parts += ['', 'Scope: ' + ', '.join(f'`{g}`' for g in globs) + '.']
        content = ('\n'.join(parts).rstrip() + '\n').encode()
        path = f'antigravity/plugins/{kit}/rules/AGENTS.md'
        if len(content) > RULES_LIMIT:
            raise ValueError(f'{path} is {len(content)} bytes, over the {RULES_LIMIT} byte rules limit')
        return Output(path, content)
